"""Report assembly: fixed structure, facts from code, interpretation from the model.

Mirrors the report structure of design.md 10.3:

    1.  question and spec (with each field's provenance)
    2.  estimand and the population it applies to
    3.  variable-role diagram
    4.  assumptions, split by category, **before the results**
    5.  data quality
    6.  primary results
    7.  sensitivity and refutation
    8.  claim level and reasoning
    9.  limitations
    10. post-hoc analyses, if any

Two properties this layer enforces:

**The order is not negotiable.** "Assumptions before results" is a structural
guarantee, not a reminder, section order comes from ``SECTION_ORDER`` and the model
cannot change it. A reader sees what the analysis rests on before they see a number.

**Some sections are out of the model's reach.** The spec-provenance table and the
claim-level decision are generated by code. The first is design.md 7.1's mitigation
for "the server cannot verify that the user really confirmed anything", it has to
reflect the spec faithfully, and it loses its point if the model touches it. The
second is where principle 5 lands: the model may not upgrade its own wording. The
model may write interpretation for the sections in ``MODEL_AUTHORED_SECTIONS`` only,
and that prose always goes through placeholder rendering.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from enum import StrEnum
from typing import Any

from causpec.core.contracts.manifest import ExecutionMode
from causpec.core.contracts.quality import QualityReport, Severity
from causpec.core.contracts.spec import AssumptionCategory, Spec
from causpec.core.reporting import diagram
from causpec.core.reporting.claim_level import ClaimLevelDecision, load_rules
from causpec.core.reporting.render import render


class Section(StrEnum):
    """The report's ten sections (design.md 10.3)."""

    QUESTION_AND_SPEC = "question_and_spec"
    ESTIMAND = "estimand"
    VARIABLE_ROLES = "variable_roles"
    ASSUMPTIONS = "assumptions"
    DATA_QUALITY = "data_quality"
    PRIMARY_RESULTS = "primary_results"
    SENSITIVITY = "sensitivity"
    CLAIM_LEVEL = "claim_level"
    LIMITATIONS = "limitations"
    POST_HOC = "post_hoc"


# The order is design.md 10.3. Assumptions (4) preceding primary results (6) is the point.
SECTION_ORDER: tuple[Section, ...] = tuple(Section)

TITLES: dict[Section, str] = {
    Section.QUESTION_AND_SPEC: "Question and analysis spec",
    Section.ESTIMAND: "Estimand and the population it applies to",
    Section.VARIABLE_ROLES: "Variable roles",
    Section.ASSUMPTIONS: "Assumptions",
    Section.DATA_QUALITY: "Data quality",
    Section.PRIMARY_RESULTS: "Primary results",
    Section.SENSITIVITY: "Sensitivity and refutation",
    Section.CLAIM_LEVEL: "Claim level and reasoning",
    Section.LIMITATIONS: "Limitations",
    Section.POST_HOC: "Post-hoc analyses",
}

# Sections for which the model may supply interpretation. Everything else is code-generated.
MODEL_AUTHORED_SECTIONS: frozenset[Section] = frozenset(
    {
        Section.ESTIMAND,
        Section.DATA_QUALITY,
        Section.PRIMARY_RESULTS,
        Section.SENSITIVITY,
        Section.LIMITATIONS,
        Section.POST_HOC,
    }
)

CATEGORY_TITLES: dict[AssumptionCategory, str] = {
    AssumptionCategory.EMPIRICALLY_ASSESSED: "Assessable from the data",
    AssumptionCategory.REQUIRES_JUSTIFICATION: "Require justification",
    AssumptionCategory.UNTESTABLE: "Untestable",
}

SEVERITY_MARKS: dict[Severity, str] = {
    Severity.BLOCKING: "FAIL (blocking)",
    Severity.WARNING: "WARN",
    Severity.INFO: "pass",
}


class ReportError(Exception):
    """Report assembly failed."""


def _escape(value: object) -> str:
    """Escape pipes for Markdown tables, or "max |SMD|" splits a column in two."""
    return str(value).replace("|", "\\|").replace("\n", " ")


def _spec_section(
    spec: Spec,
    execution_mode: ExecutionMode,
    provenance: Mapping[str, Any] | None = None,
) -> str:
    """The spec in full, with each field's provenance.

    design.md 7.1: confirmation happens in conversation, and the server cannot verify
    that the user ever saw the spec. This table is the mitigation, it puts each
    field's source, the user's own words and the turn number in front of them, to be
    checked after the fact. It is therefore generated from the spec by code, with the
    model nowhere in the path.
    """
    lines = [f"**Question**: {spec.question}", ""]
    if execution_mode is ExecutionMode.SKILL:
        lines += [
            "> Note: this run used the skill form (best-effort). The agent is able to "
            "bypass the scripts and read the data directly, so the guarantees below are "
            "weaker than in MCP form.",
            "",
        ]
    lines += [
        "Each spec field, with its value and provenance. **Confirmation happened in "
        "conversation and the system cannot verify that the user actually read any of "
        "it**, please check each row, especially whether the quoted words are really "
        "yours.",
        "",
        "| Field | Value | Source | Status | User's words | Turn |",
        "|---|---|---|---|---|---|",
    ]
    for name, field in spec.fields.items():
        lines.append(
            f"| `{name}` | {_escape(field.value)} | {field.source.value} | "
            f"{field.status.value} | {_escape(field.said or '(none)')} | "
            f"{field.turn or '(none)'} |"
        )
    lines += ["", f"spec hash: `{spec.spec_hash()}`"]
    lines += _provenance_lines(provenance or {})
    return "\n".join(lines)


def _provenance_lines(provenance: Mapping[str, Any]) -> list[str]:
    """The data fingerprints, and whether this data has been analysed before.

    The fingerprints are over normalised content, so the same numbers re-exported in a
    different column order give the same value: they answer "is this the same data?" the way a
    person means it.

    The earlier-runs line is the one that matters. design.md 7.4 locks the primary analysis at
    confirmation, and a reader cannot apply that rule without knowing whether these numbers
    are the first look at this data or the fourth. It is stated, never refused: a second
    analysis is legitimate and common, it just has to be visible as one. Runs that stopped at
    a gate do not count, because a user who cleared a blocking issue and re-ran was not
    reacting to a result.
    """
    source = provenance.get("source_fingerprint")
    snapshot = provenance.get("snapshot_fingerprint")
    if not source and not snapshot:
        return []
    lines = [""]
    if source:
        lines.append(f"source data fingerprint: `{source}`")
    if snapshot and snapshot != source:
        lines.append(
            f"analysed table fingerprint: `{snapshot}` (after the preprocessing steps and "
            f"the population filters)"
        )
    prior = list(provenance.get("prior_runs") or [])
    if prior:
        lines += [
            "",
            f"**This data has been analysed before.** {len(prior)} earlier run(s) reached an "
            f"estimate on the same source data under a different spec:",
        ]
        lines += [f"- {entry}" for entry in prior]
        lines.append(
            "The primary analysis is the first one (design.md 7.4). Treat what follows as a "
            "further look at numbers that have already been seen, and read any difference in "
            "the spec as a choice made with those numbers in view."
        )
    return lines


def _assumptions_section(spec: Spec) -> str:
    """Assumptions by category. **Before the results** (design.md 10.3)."""
    if not spec.assumptions:
        return (
            "_This analysis declares no identification assumptions. That is itself a "
            "problem: without assumptions there is no identification._"
        )

    lines: list[str] = []
    for category in AssumptionCategory:
        group = [a for a in spec.assumptions if a.category is category]
        if not group:
            continue
        lines += [f"### {CATEGORY_TITLES[category]}", ""]
        if category is AssumptionCategory.UNTESTABLE:
            lines += [
                "_These assumptions **cannot be verified by data in principle**. No "
                "number of diagnostics will establish them; a person has to argue for "
                "them and carry the responsibility._",
                "",
            ]
        for assumption in group:
            lines.append(f"- **{assumption.id}**, {assumption.statement}")
            if assumption.justification:
                who = assumption.justified_by.value if assumption.justified_by else "unattributed"
                lines.append(f"  - Justification ({who}): {assumption.justification}")
            elif category is AssumptionCategory.UNTESTABLE:
                lines.append("  - **No justification given.**")
        lines.append("")
    return "\n".join(lines).rstrip()


def _exclusion_ledger(ledger: Sequence[Mapping[str, Any]]) -> str:
    """Who was excluded and by what, in the form a reader of a study already audits.

    This is the one table a reader checks before any estimate: an effect measured on 2,800
    of 3,000 patients is an effect for whoever those 2,800 are. The counts come from the
    filters actually applied, so the ledger cannot drift from what ran.
    """
    if not ledger:
        return ""
    lines = [
        "**Who the analysis is about.** Each row is a criterion from the spec, in the order "
        "it was applied, with the user's own words for why.",
        "",
        "| Criterion | Said | Before | Excluded | After |",
        "|---|---|---|---|---|",
    ]
    for row in ledger:
        lines.append(
            f"| `{row['criterion']}` | {_escape(str(row['said']))} | {row['n_before']:,} "
            f"| {row['n_removed']:,} | {row['n_after']:,} |"
        )
    return "\n".join(lines)


def _quality_section(
    report: QualityReport,
    preprocessing: Sequence[str] = (),
    ledger: Sequence[Mapping[str, Any]] = (),
) -> str:
    """The checks, preceded by what was done to the data before they ran.

    The order is the point. A reader who sees the checks first and the transformations
    afterwards has already formed a view about a table that no longer exists. The exclusion
    ledger comes first of all, because every number below it describes the population it
    leaves behind.
    """
    lines: list[str] = []
    ledger_table = _exclusion_ledger(ledger)
    if ledger_table:
        lines += [ledger_table, ""]
    if preprocessing:
        lines += [
            "**Before these checks ran, the following was applied to a working copy of the "
            "data, with the user's agreement recorded in the spec. The source was not "
            "modified.**",
            "",
        ]
        lines += [f"- {step}" for step in preprocessing]
        lines += [""]
    if not report.issues:
        return "\n".join([*lines, "_No quality checks were run._"]).strip()
    lines += ["| Check | Result | Summary |", "|---|---|---|"]
    for issue in report.issues:
        lines.append(
            f"| `{issue.check_id}` | {SEVERITY_MARKS[issue.severity]} | {_escape(issue.summary)} |"
        )
    failing = [i for i in report.issues if i.evidence.get("passed") is False]
    if failing:
        lines += ["", "Checks that did not pass, and what they mean:"]
        for issue in failing:
            lines.append(f"- **{issue.check_id}**: {issue.impact_on_analysis}")
            if issue.recommended_repair:
                lines.append(f"  - Suggested: {issue.recommended_repair}")
    return "\n".join(lines)


def _roles_section(spec: Spec) -> str:
    """The derived diagram, the roles it came from, and what it cannot say.

    Derived rather than drawn: the user declares a role per variable or group and the edges
    follow, which is what lets `roles_match_adjustment` compare the picture with the analysis.
    A full DAG over forty ICU covariates is a formality nobody reads (design.md 7.5).
    """
    if not spec.variable_roles:
        return _not_implemented(
            "No variable roles were declared, so no diagram could be derived. This",
            "design.md 7.5",
        )
    lines = [
        "Each variable or group was given a role at confirmation, and the diagram below is "
        "derived from those roles: the edges are not drawn by hand, so the picture and the "
        "analysis cannot disagree without `roles_match_adjustment` saying so.",
        "",
        diagram.mermaid(spec),
        "",
        "| Variable or group | Role |",
        "|---|---|",
    ]
    for variable, role in sorted(spec.variable_roles.items()):
        lines.append(f"| `{variable}` | {role.replace('_', ' ')} |")
    if spec.key_non_edges:
        lines += ["", "Assumed absent, and the identification rests on each:"]
        lines += [f"- {statement}" for statement in spec.key_non_edges]
    lines += [
        "",
        "**What this diagram cannot express.** Causal relations among the covariates "
        "themselves, for example a variable declared as a confounder that is really a "
        "mediator of another confounder. That needs a full DAG over every column, which is "
        "not asked for here: over dozens of covariates it produces a formality rather than a "
        "statement anyone has checked. What is checked is the part that decides "
        "identification, which is each variable's role and the few assumed-absent edges.",
    ]
    return "\n".join(lines)


def _sensitivity_section(
    sensitivity: Mapping[str, Any] | None,
    addresses: Mapping[str, float | int | str],
) -> str:
    """The refutation verdicts and the E-value, with what each cannot say.

    Both are stated as code-generated findings rather than left to prose, for the same reason
    the quality table is: a refutation that failed is the single most important line in a
    report, and a sentence is where it goes missing.
    """
    if sensitivity is None:
        return _not_implemented("Sensitivity and refutation testing", "design.md 10.1")
    skipped = str(sensitivity.get("skipped_because") or "")
    lines: list[str] = []
    findings = list(sensitivity.get("findings") or [])
    if skipped:
        lines += [f"**No refutation test ran.** {skipped}", ""]
    elif findings:
        lines += [
            "Each test changes one thing whose correct answer is known in advance, re-runs "
            "the same estimator, and checks that the known answer comes back. None of them "
            "can say the effect is real; they can say the machinery is not inventing one.",
            "",
            "| Test | Result | What happened |",
            "|---|---|---|",
        ]
        for finding in findings:
            mark = "pass" if finding.get("passed") else "**FAIL**"
            lines.append(
                f"| `{finding.get('test_id')}` | {mark} | {_escape(finding.get('summary', ''))} |"
            )
        lines += [""]
        for finding in findings:
            if finding.get("interpretation"):
                lines.append(f"- **{finding.get('test_id')}**: {finding['interpretation']}")
        lines += [""]

    absent = str(sensitivity.get("e_value_absent_because") or "")
    if absent:
        lines += [f"**No E-value.** {absent}", ""]
    elif "res:sensitivity.e_value" in addresses:
        point = addresses["res:sensitivity.e_value"]
        ratio = addresses.get("res:sensitivity.risk_ratio", "n/a")
        lines += [
            f"**E-value for the estimate: {point}** (risk ratio {ratio}). An unmeasured "
            f"confounder would have to be associated with both the treatment and the outcome "
            f"by at least this risk ratio each, beyond every covariate already adjusted for, "
            f"to move the estimate to no effect.",
            "",
        ]
        if "res:sensitivity.e_value_limit" in addresses:
            includes = str(addresses.get("res:sensitivity.interval_includes_null", "no")) == "yes"
            limit = addresses["res:sensitivity.e_value_limit"]
            lines.append(
                f"**E-value for the confidence limit: {limit}.** This is the number to read: "
                f"it is what it would take to make the result merely compatible with no "
                f"effect, which is a weaker and more honest claim than moving the point "
                f"estimate."
                if not includes
                else "**The interval already includes no effect**, so the E-value for the "
                "limit is 1: no unmeasured confounding at all is needed for this result to "
                "be compatible with nothing."
            )
            lines.append("")
        lines.append(
            "Whether a confounder that strong is plausible is a question for someone who "
            'knows this setting. The E-value turns "could confounding explain this?" into '
            '"could a confounder this strong exist?", which is answerable; it does not '
            "answer it."
        )
    return "\n".join(lines).strip() or _not_implemented(
        "Sensitivity and refutation testing", "design.md 10.1"
    )


def _claim_level_section(decision: ClaimLevelDecision) -> str:
    """Claim level and reasoning. Code-generated, principle 5: no self-upgrading."""
    wording = load_rules()["wording"][decision.level.value]
    lines = [
        f"**Claim level for this analysis: `{decision.level.value}`**",
        "",
        f"What this level permits: {wording}",
        "",
    ]
    if decision.reasons:
        lines.append("Reasoning:")
        lines += [f"- {reason}" for reason in decision.reasons]
        lines.append("")
    lines.append(
        f"Decision rules version {decision.rules_version}, rules file hash `{decision.rules_hash}`."
    )
    return "\n".join(lines)


def _tables_section(
    tables: Sequence[Mapping[str, Any]], addresses: Mapping[str, float | int | str]
) -> str:
    """Render the result tables a family declares, from the merged address table.

    Core stays family-agnostic: a family declares what its table looks like in
    ``family.yaml`` and this renders it from addresses, the same way the renderer
    substitutes a placeholder. Nothing here knows what a lag is.

    A table exists because some results do not fit in prose. A lag profile is the case
    that forced it: its finding is the shape across lags, and leaving that to the model's
    sentences means the reader sees the lags the model chose to mention. The declaration
    promised the per-lag counts; this is what keeps that promise.
    """
    chunks: list[str] = []
    for table in tables:
        rows = table.get("rows", {})
        variable = str(rows.get("variable", "i"))
        start = int(rows.get("from", 0))
        through = rows.get("through_address")
        last = _as_int(addresses.get(str(through))) if through is not None else None
        if last is None:
            last = int(rows.get("through", start))
        columns = list(table.get("columns", []))
        if not columns or last < start:
            continue
        headers = [str(column.get("header", "")) for column in columns]
        lines = [f"**{table.get('title', 'Results')}**", ""]
        lines.append("| " + " | ".join(headers) + " |")
        lines.append("|" + "|".join(["---"] * len(headers)) + "|")
        for index in range(start, last + 1):
            cells: list[str] = []
            for column in columns:
                cells.append(_table_cell(column, variable, index, addresses))
            lines.append("| " + " | ".join(cells) + " |")
        if table.get("note"):
            lines += ["", str(table["note"]).strip()]
        chunks.append("\n".join(lines))
    return "\n\n".join(chunks)


def _table_cell(
    column: Mapping[str, Any],
    variable: str,
    index: int,
    addresses: Mapping[str, float | int | str],
) -> str:
    """One cell: either the row's own index, or a formatted value at an address."""
    if "address" not in column:
        return str(index)
    address = str(column["address"]).replace("{" + variable + "}", str(index))
    if address not in addresses:
        return "n/a"
    value = addresses[address]
    spec = column.get("format")
    if spec is None or isinstance(value, str):
        return _escape(value)
    try:
        return format(value, str(spec))
    except (TypeError, ValueError):
        return _escape(value)


def _as_int(value: object) -> int | None:
    try:
        return int(float(str(value)))
    except (TypeError, ValueError):
        return None


def _not_implemented(what: str, where: str) -> str:
    """Say so rather than silently omitting, the reader needs to know what is missing."""
    return (
        f"_{what} is not implemented yet (see {where}). An empty section here does "
        f"**not** mean the check passed._"
    )


def build(
    spec: Spec,
    quality: QualityReport,
    decision: ClaimLevelDecision,
    addresses: Mapping[str, float | int | str],
    *,
    narrative: Mapping[Any, str] | None = None,
    tables: Sequence[Mapping[str, Any]] | None = None,
    preprocessing: Sequence[str] | None = None,
    exclusions: Sequence[Mapping[str, Any]] | None = None,
    provenance: Mapping[str, Any] | None = None,
    sensitivity: Mapping[str, Any] | None = None,
    execution_mode: ExecutionMode = ExecutionMode.CLI,
    title: str | None = None,
) -> str:
    """Assemble the full report.

    Args:
        narrative: interpretation written by the model, keyed by section. Only
            sections in ``MODEL_AUTHORED_SECTIONS`` are accepted, and the prose always
            goes through placeholder rendering, a bare number fails the render.
        tables: result-table declarations from the family, rendered into the primary
            results section ahead of the model's prose. Declared rather than coded, so
            core needs to know nothing about any family.
        preprocessing: what the agreed preprocessing steps actually did, printed above the
            quality table. Every number below them was computed on the transformed copy, so
            a reader who does not know that is reading the wrong table.
        exclusions: the exclusion ledger, one row per population filter. Printed above
            everything else in the data section: an estimate computed on 2,800 of 3,000
            patients is an estimate for whoever those 2,800 are.
        provenance: the data fingerprints and any earlier runs on the same data, printed
            under the spec table. Whether these numbers have been looked at before is part
            of how strongly they can be read (design.md 7.4).
        sensitivity: the refutation findings and the E-value, as a mapping, so core renders
            them without importing the sensitivity module's dataclasses into this one.

    Raises:
        ReportError: the model tried to author a purely factual section.
        RenderError: the prose contains a bare number or an unknown address.
    """
    provided = {Section(key): text for key, text in (narrative or {}).items()}
    forbidden = sorted(s.value for s in provided if s not in MODEL_AUTHORED_SECTIONS)
    if forbidden:
        raise ReportError(
            f"These sections are generated by code and do not accept model-written "
            f"prose: {', '.join(forbidden)}.\n"
            f"The spec-provenance table exists so a person can audit it, and the "
            f"claim-level decision belongs to the code (design.md 7.1, principle 5). "
            f"Writable sections: "
            f"{', '.join(sorted(s.value for s in MODEL_AUTHORED_SECTIONS))}."
        )

    facts: dict[Section, str] = {
        Section.QUESTION_AND_SPEC: _spec_section(spec, execution_mode, provenance),
        Section.ASSUMPTIONS: _assumptions_section(spec),
        Section.DATA_QUALITY: _quality_section(quality, preprocessing or [], exclusions or []),
        Section.CLAIM_LEVEL: _claim_level_section(decision),
        Section.VARIABLE_ROLES: _roles_section(spec),
        Section.SENSITIVITY: _sensitivity_section(sensitivity, addresses),
    }
    if tables:
        rendered_tables = _tables_section(tables, addresses)
        if rendered_tables:
            facts[Section.PRIMARY_RESULTS] = rendered_tables

    chunks = [f"# {title or spec.question}", ""]
    for section in SECTION_ORDER:
        body_parts = [facts[section]] if section in facts else []
        if section in provided:
            body_parts.append(render(provided[section], addresses))
        if not body_parts:
            if section is Section.POST_HOC:
                continue  # no post-hoc analyses, no section
            body_parts = ["_(nothing in this section)_"]
        chunks += [f"## {TITLES[section]}", "", "\n\n".join(body_parts), ""]
    return "\n".join(chunks).rstrip() + "\n"
