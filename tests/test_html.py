"""The report as a web page.

Why this exists at all: the report is Markdown, and `open report.md` hands the file to
whatever that machine associates with `.md`. On the author's laptop that is an editor; on a
colleague's it may be nothing. A browser is the one renderer everyone has, so the report can
also be written as a self-contained page.

The converter is deliberately narrow. Its input is not arbitrary Markdown, it is what
`report.py` emits, and these tests pin exactly that set of constructs plus the two properties
that matter when a report is turned into HTML:

**Nothing disappears.** A construct the converter does not recognise becomes a paragraph of
visible text, because a reader who cannot see a section cannot know it was there.

**Nothing is executed.** A report carries a user's own words, quoted from the spec, and a
column name they chose. Both reach the page as text.
"""

from __future__ import annotations

from causpec.core.reporting.html import to_html


def test_the_page_is_self_contained() -> None:
    """No stylesheet to fetch, no font to install, nothing to serve it from: the file is
    opened from disk and has to work with no network at all."""
    page = to_html("# A title\n\nSome prose.\n")
    assert page.startswith("<!doctype html>")
    assert "<style>" in page
    assert "<h1>A title</h1>" in page
    assert "<p>Some prose.</p>" in page
    assert "http" not in page.split("<style>")[0]


def test_every_construct_the_report_emits_survives() -> None:
    markdown = """# Report

## A section

A paragraph that **bolds** a phrase and names `a_column`.

| Check | Result |
|---|---|
| `backdoor_overlap` | pass |

- first item
- second item
  - a nested one

> Something the model said out loud.

---

### Deeper

```
plain code
```
"""
    page = to_html(markdown)
    for fragment in (
        "<h1>Report</h1>",
        "<h2>A section</h2>",
        "<h3>Deeper</h3>",
        "<strong>bolds</strong>",
        "<code>a_column</code>",
        "<th>Check</th>",
        "<td><code>backdoor_overlap</code></td>",
        "<li>first item</li>",
        "<blockquote>",
        "<hr>",
        "<pre><code>plain code</code></pre>",
    ):
        assert fragment in page, fragment
    # The nested bullet is a list inside a list rather than a lost line.
    assert page.count("<ul>") == 2
    assert "a nested one" in page


def test_a_table_cell_holding_an_escaped_pipe_keeps_its_columns() -> None:
    """`max |SMD|` is a real summary, and the report escapes the pipes so a table row does
    not split into extra columns. The split that finds the cells has to respect that."""
    page = to_html("| Check | Summary |\n|---|---|\n| `smd` | max \\|SMD\\| is 0.04 |\n")
    assert page.count("<td>") == 2
    assert "max |SMD| is 0.04" in page


def test_the_quality_table_keeps_every_row() -> None:
    rows = "\n".join(f"| `check_{i}` | pass | fine |" for i in range(12))
    page = to_html(f"| Check | Result | Summary |\n|---|---|---|\n{rows}\n")
    assert page.count("<tr>") == 13  # one header plus twelve findings


def test_the_diagram_is_handed_to_mermaid_and_readable_without_it() -> None:
    """With no network the script does not load and the browser shows the source, so a
    reader sees the roles either way. That is the only reason a CDN is acceptable here."""
    page = to_html("## Variable roles\n\n```mermaid\ngraph LR\n  T --> Y\n```\n")
    assert '<pre class="mermaid">graph LR\n  T --&gt; Y</pre>' in page
    assert "mermaid.esm.min.mjs" in page


def test_no_mermaid_script_when_there_is_no_diagram() -> None:
    """The stylesheet always carries the rule, which costs nothing; the script is fetched
    from a CDN, so a report with no diagram asks the network for nothing."""
    page = to_html("# Report\n\nNo diagram here.\n")
    assert "<script" not in page
    assert "cdn.jsdelivr.net" not in page


def test_markup_in_the_user_s_own_words_is_escaped_rather_than_run() -> None:
    """The spec table quotes what the user typed, and a report is a file people send each
    other. A column named `<script>` is a silly name and not a way to run anything."""
    page = to_html("| Field | User's words |\n|---|---|\n| `t` | <script>alert(1)</script> |\n")
    assert "<script>alert(1)</script>" not in page
    assert "&lt;script&gt;" in page


def test_an_html_comment_passes_through() -> None:
    """The committed example carries a provenance header saying which commands made it."""
    page = to_html("<!-- generated by the quickstart -->\n\n# Report\n")
    assert "<!-- generated by the quickstart -->" in page


def test_the_title_is_one_line() -> None:
    """A question folded across lines in the spec arrives with newlines in it, and a browser
    tab is one line."""
    page = to_html("# Report\n", title="What does dialysis\ndo to mortality?\n")
    assert "<title>What does dialysis do to mortality?</title>" in page


def test_an_empty_report_is_still_a_page() -> None:
    page = to_html("")
    assert page.startswith("<!doctype html>")
    assert page.rstrip().endswith("</html>")
